# 2. 한국투자증권 API 클래스
# ==============================================================================
class KisApi:
    def __init__(self):
        self.base_url = Config.URL_BASE
        self.headers = {"content-type": "application/json"}
        self.access_token = self.get_access_token()

    # [인증] 토큰 발급
    def get_access_token(self):
        path = "oauth2/tokenP"
        url = f"{self.base_url}/{path}"
        body = {
            "grant_type": "client_credentials",
            "appkey": Config.APP_KEY,
            "appsecret": Config.APP_SECRET
        }
        res = requests.post(url, headers=self.headers, data=json.dumps(body))

        if res.status_code == 200:
            token = res.json()['access_token']
            print(f"접근 토큰 발급 성공")
            return f"Bearer {token}"
        else:
            print(f"토큰 발급 실패: {res.text}")
            return None

    # [공통] 헤더 생성 (주문/조회 시 필요)
    def get_common_headers(self, tr_id):
        return {
            "authorization": self.access_token,
            "appkey": Config.APP_KEY,
            "appsecret": Config.APP_SECRET,
            "tr_id": tr_id,
            "custtype": "P", # 개인
        }

    # [조회] 주식 현재가 조회 (매수 수량 계산용)
    def get_current_price(self, code):
        path = "uapi/domestic-stock/v1/quotations/inquire-price"
        url = f"{self.base_url}/{path}"

        headers = self.get_common_headers("FHKST01010100") # 현재가 조회 TR ID
        params = {
            "fid_cond_mrkt_div_code": "J", # 주식, ETF 등
            "fid_input_iscd": code # 종목코드
        }

        res = requests.get(url, headers=headers, params=params)
        if res.status_code == 200 and res.json()['rt_cd'] == '0':
            price = int(res.json()['output']['stck_prpr']) # 현재가
            return price
        else:
            print(f"현재가 조회 실패 ({code}): {res.text}")
            return None

    # [주문] 주식 매수 주문 (시장가)
    def buy_stock(self, code, qty):
        path = "uapi/domestic-stock/v1/trading/order-cash"
        url = f"{self.base_url}/{path}"

        # 모의투자 매수 TR ID: VTTC0802U (실전은 TTTC0802U)
        headers = self.get_common_headers("VTTC0802U")

        data = {
            "CANO": Config.CANO,
            "ACNT_PRDT_CD": Config.ACNT_PRDT_CD,
            "PDNO": code,           # 종목코드
            "ORD_DVSN": "01",       # 주문구분 (00:지정가, 01:시장가) -> 모의투자라 시장가로 체결
            "ORD_QTY": str(qty),    # 주문수량
            "ORD_UNPR": "0",        # 주문단가 (시장가는 0)
        }

        res = requests.post(url, headers=headers, data=json.dumps(data))
        return res.json()

