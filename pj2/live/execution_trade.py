# 3. 메인 실행 로직 (CSV 읽기 -> 계산 -> 매수)
# ==============================================================================
def run_auto_buy():
    print("[모의투자] 자동 매수 프로그램을 시작합니다...")

    # 1. API 연결
    kis = KisApi()
    if not kis.access_token:
        return

    # 2. CSV 파일 읽기
    try:
        df = pd.read_csv("buy_list.csv", dtype={'code': str}) # 코드는 문자로 읽기
        print(f"\n매수 리스트 로드 완료: {len(df)}개 종목")
    except FileNotFoundError:
        print("'buy_list.csv' 파일을 찾을 수 없습니다.")
        return

    # 3. 종목별 순회하며 매수
    total_cash = Config.TOTAL_INVESTMENT_AMOUNT
    print(f"총 투자 금액: {total_cash:,.0f}원\n")

    for idx, row in df.iterrows():
        code = row['code']
        weight = row['weight']

        # 종목코드 보정 (혹시 .KS 등이 붙어있다면 제거)
        code = code.split('.')[0]

        # 3-1. 현재가 조회
        current_price = kis.get_current_price(code)
        if current_price is None:
            continue

        # 3-2. 매수 수량 계산 (투자금 * 비중 / 현재가) -> 내림 처리
        target_amount = total_cash * weight
        buy_qty = int(target_amount // current_price)

        if buy_qty <= 0:
            print(f"⚠️ {code}: 주문 가능 수량이 0주입니다. (배정금액: {target_amount:,.0f}원)")
            continue

        print(f"[{idx+1}/{len(df)}] {code} 주문 준비: 현재가 {current_price:,}원 | 목표 {weight*100}% | 수량 {buy_qty}주")

        # 3-3. 매수 주문 실행
        result = kis.buy_stock(code, buy_qty)

        if result['rt_cd'] == '0':
            print(f"   ✅ 매수 주문 성공! (주문번호: {result['output']['ODNO']})")
            # 로그 파일에 기록 (증빙용)
            with open("buy_log.txt", "a", encoding="utf-8") as f:
                f.write(f"{datetime.now()} | 매수성공 | {code} | {buy_qty}주 | {current_price}원\n")
        else:
            print(f"   ❌ 매수 실패: {result['msg1']}")

        # API 과부하 방지를 위한 대기
        time.sleep(0.2)

    print("\n🏁 모든 주문 처리가 완료되었습니다.")

if __name__ == "__main__":
    run_auto_buy()